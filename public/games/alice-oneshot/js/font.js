  var H = 8;
  var GAP = 1;
  var LINE = 10;

  // --- build a white atlas once -------------------------------------
  var order = Object.keys(G);
  var meta = {};
  var totalW = 0;
  for (var i = 0; i < order.length; i++) {
    var w = G[order[i]][0].length;
    meta[order[i]] = { x: totalW, w: w };
    totalW += w + 1;
  }

  var atlas = document.createElement('canvas');
  atlas.width = Math.max(1, totalW);
  atlas.height = H;
  (function buildAtlas() {
    var ctx = atlas.getContext('2d');
    var img = ctx.createImageData(atlas.width, H);
    var d = img.data;
    for (var gi = 0; gi < order.length; gi++) {
      var ch = order[gi], rows = G[ch], ox = meta[ch].x;
      for (var y = 0; y < H; y++) {
        var row = rows[y];
        for (var x = 0; x < row.length; x++) {
          if (row[x] !== '#') continue;
          var p = ((y * atlas.width) + (ox + x)) * 4;
          d[p] = 255; d[p + 1] = 255; d[p + 2] = 255; d[p + 3] = 255;
        }
      }
    }
    ctx.putImageData(img, 0, 0);
  })();

  var tintCache = {};
  function tinted(color) {
    if (tintCache[color]) return tintCache[color];
    var c = document.createElement('canvas');
    c.width = atlas.width; c.height = atlas.height;
    var x = c.getContext('2d');
    x.drawImage(atlas, 0, 0);
    x.globalCompositeOperation = 'source-in';
    x.fillStyle = color;
    x.fillRect(0, 0, c.width, c.height);
    tintCache[color] = c;
    return c;
  }

  function glyph(ch) {
    return meta[ch] || meta[' '];
  }

  function width(text, scale) {
    scale = scale || 1;
    var lines = String(text).split('\n');
    var best = 0;
    for (var l = 0; l < lines.length; l++) {
      var w = 0, s = lines[l];
      for (var i = 0; i < s.length; i++) w += glyph(s[i]).w + GAP;
      if (w > 0) w -= GAP;
      if (w > best) best = w;
    }
    return best * scale;
  }

  function height(text, scale) {
    scale = scale || 1;
    var n = String(text).split('\n').length;
    return (n * LINE - (LINE - H)) * scale;
  }

  function draw(ctx, text, x, y, color, scale) {
    scale = scale || 1;
    var src = tinted(color);
    var lines = String(text).split('\n');
    for (var l = 0; l < lines.length; l++) {
      var s = lines[l];
      var cx = x;
      var cy = y + l * LINE * scale;
      for (var i = 0; i < s.length; i++) {
        var g = glyph(s[i]);
        if (s[i] !== ' ') {
          ctx.drawImage(src, g.x, 0, g.w, H, cx, cy, g.w * scale, H * scale);
        }
        cx += (g.w + GAP) * scale;
      }
    }
  }

  // Text with a soft 1px drop shadow - keeps small type readable on grass.
  function drawShadow(ctx, text, x, y, color, shadow, scale) {
    scale = scale || 1;
    draw(ctx, text, x, y + scale, shadow, scale);
    draw(ctx, text, x, y, color, scale);
  }

  function drawCentered(ctx, text, cx, y, color, scale) {
    draw(ctx, text, Math.round(cx - width(text, scale) / 2), y, color, scale);
  }

  function drawCenteredShadow(ctx, text, cx, y, color, shadow, scale) {
    var x = Math.round(cx - width(text, scale) / 2);
    drawShadow(ctx, text, x, y, color, shadow, scale);
  }

  function drawRight(ctx, text, rx, y, color, scale) {
    draw(ctx, text, Math.round(rx - width(text, scale)), y, color, scale);
  }

  AG.Font = {
    H: H, LINE: LINE,
    width: width, height: height,
    draw: draw, drawShadow: drawShadow,
    drawCentered: drawCentered, drawCenteredShadow: drawCenteredShadow,
    drawRight: drawRight
  };
